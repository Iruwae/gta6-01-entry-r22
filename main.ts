import {cpSync, mkdirSync, rmSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {buildDossier} from './vendor/makefun-game.ts';
const out = process.env.MAKEFUN_OUTPUT_DIR || './out';
rmSync(out, {recursive: true, force: true});
mkdirSync(out, {recursive: true});
cpSync('game', out + '/game', {recursive: true});
cpSync('screenshots', out + '/screenshots', {recursive: true});
const bytes = buildDossier(out, {text_max_bytes: 163840, screenshots_max_count: 4, screenshot_max_bytes: 262144, game_max_files: 993, game_max_bytes: 50331648, game_path_max_bytes: 1000});
writeFileSync('dossier.json', bytes);
const hash = createHash('sha256').update(bytes).digest('hex');
const text = new TextDecoder().decode(bytes);
if (text.includes('left out')) throw new Error('dossier has left-out files');
console.log('dossier bytes:', bytes.length);
console.log('dossier sha256:', hash);
